// Build shared/exercise-lib.json (+ a .js wrapper the app can load from file://) from a
// LOCAL clone of hasaneyldrm/exercises-dataset.
//
//   git clone --depth 1 https://github.com/hasaneyldrm/exercises-dataset.git /tmp/exercises-dataset
//   node scripts/build-exercise-lib.mjs /tmp/exercises-dataset
//
// Licensing: the dataset's exercise TEXT is MIT (© Hasan Emir Yıldırım) and is what we
// keep. Its images and GIFs are © Gym visual under separate terms — this script never
// reads, copies or references them (no image/gif_url/media_id fields are emitted).
//
// What's kept: every `band` / `resistance band` exercise, plus body-weight exercises that
// need no kit beyond the floor (no bar, bench, box, ball, machine…). The athlete owns five
// loop bands and a Peloton and nothing else — the CLAUDE.md kit rules still win over
// anything in here; this is a menu of ideas and muscle tags, not a prescription source.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import '../shared/muscle-core.js';

const M = globalThis.MuscleCore;
const repo = process.argv[2];
if (!repo) { console.error('usage: node scripts/build-exercise-lib.mjs <path to exercises-dataset clone>'); process.exit(1); }
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const data = JSON.parse(readFileSync(join(repo, 'data', 'exercises.json'), 'utf8'));

// Body-weight moves that secretly need equipment this athlete doesn't have.
const NEEDS_KIT = /pull[- ]?up|chin[- ]?up|\bdips?\b|bench|\bbar\b|barbell|hanging|\brings?\b|\bbox\b|sled|machine|stability|wall|towel|chair|\bstep\b|incline|decline|smith|rope|trx|suspension|assisted|weighted|bosu|roller|\bball\b|bike|elliptical|treadmill|parallel|table|sofa|bed\b|dumbbell|kettlebell|cable|plate|swiss|gymnastic|hyperextension|captain|sling|lever|\bflag\b|balance board|muscle-?up|pole/i;

const keep = data.filter(e => {
  if (e.equipment === 'band' || e.equipment === 'resistance band') return true;
  if (e.equipment !== 'body weight') return false;
  if (e.target === 'cardiovascular system') return false;
  return !NEEDS_KIT.test(e.name);
});

const steps = e => {
  const s = e.instruction_steps && e.instruction_steps.en;
  if (Array.isArray(s)) return s.map(String).filter(Boolean);
  const t = e.instructions && e.instructions.en;
  return t ? [String(t)] : [];
};

const exercises = keep.map(e => {
  const target = M.normalizeMuscle(e.target) || M.normalizeMuscle(e.muscle_group);
  const secondary = M.normalizeMuscles(e.secondary_muscles).filter(m => m !== target);
  return {
    id: String(e.id),
    name: String(e.name),
    equipment: e.equipment === 'resistance band' ? 'band' : e.equipment,
    bodyPart: String(e.body_part || e.category || ''),
    target,
    secondary,
    steps: steps(e),
  };
}).sort((a, b) => a.name.localeCompare(b.name));

const out = {
  source: 'https://github.com/hasaneyldrm/exercises-dataset',
  license: 'MIT — exercise text © Hasan Emir Yıldırım. No images or animations included (those are © Gym visual).',
  generated: new Date().toISOString().slice(0, 10),
  counts: { band: exercises.filter(e => e.equipment === 'band').length, bodyWeight: exercises.filter(e => e.equipment === 'body weight').length },
  exercises,
};
writeFileSync(join(root, 'shared', 'exercise-lib.json'), JSON.stringify(out, null, 1) + '\n');
// Classic-script wrapper: the app is build-free and opens from file://, where fetch() of
// a local JSON file is blocked but a <script src> is not.
writeFileSync(join(root, 'shared', 'exercise-lib.js'),
  '// GENERATED by scripts/build-exercise-lib.mjs from shared/exercise-lib.json — do not edit.\n' +
  `globalThis.EXERCISE_LIB = ${JSON.stringify(out)};\n`);
console.log(`exercise-lib: ${out.counts.band} band + ${out.counts.bodyWeight} body-weight exercises`);
